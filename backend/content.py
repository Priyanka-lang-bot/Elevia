"""Loads and validates the curriculum: subjects, topics, skills, misconceptions, questions and lessons.

The original fractions content (skill_map.json, questions.json, lessons.json) is loaded unchanged. Other
topics live in data/topics/<topic>.json (generated by scripts/build_curriculum.py) and are merged in, so the
agents see one skill graph and one question bank. data/curriculum.json lists subjects and topics.
"""
from __future__ import annotations

import json
from functools import lru_cache

from .config import DATA_DIR
from .engine import answer_input_kind, choices, is_fraction, render_prompt, validate_question

TOPICS_DIR = DATA_DIR / "topics"


def _read(path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


@lru_cache(maxsize=1)
def topic_files() -> dict[str, dict]:
    return {p.stem: _read(p) for p in sorted(TOPICS_DIR.glob("*.json"))} if TOPICS_DIR.exists() else {}


@lru_cache(maxsize=1)
def curriculum() -> dict:
    """{subjects: [...], topics: {topic_id: {...}}}. Every listed topic must have content and diagnostics."""
    data = _read(DATA_DIR / "curriculum.json")
    for sub in data["subjects"]:
        for t in sub["topics"]:
            if t not in data["topics"]:
                raise ValueError(f"Subject {sub['id']} lists unknown topic {t}")
            if data["topics"][t]["subject"] != sub["id"]:
                raise ValueError(f"Topic {t} is listed under the wrong subject")
    return data


def topics() -> dict[str, dict]:
    return curriculum()["topics"]


def topic(topic_id: str) -> dict:
    t = topics().get(topic_id)
    if t is None:
        raise KeyError(topic_id)
    return t


def topic_of_skill(skill_id: str) -> str | None:
    for tid, t in topics().items():
        if skill_id in t["skills"]:
            return tid
    return None


@lru_cache(maxsize=1)
def skill_map() -> dict:
    data = _read(DATA_DIR / "skill_map.json")
    data = {**data, "skills": list(data["skills"]), "misconceptions": dict(data["misconceptions"])}
    for tid, tf in topic_files().items():
        for s in tf["skills"]:
            data["skills"].append(s)
        for code, m in tf["misconceptions"].items():
            if code in data["misconceptions"]:
                raise ValueError(f"Duplicate misconception code {code} in topic {tid}")
            data["misconceptions"][code] = m
    if len({s["id"] for s in data["skills"]}) != len(data["skills"]):
        raise ValueError("Duplicate skill id across topics")
    ids = {s["id"] for s in data["skills"]}
    for s in data["skills"]:
        for p in s["prerequisites"]:
            if p not in ids:
                raise ValueError(f"Skill {s['id']} has unknown prerequisite {p}")
    for code, m in data["misconceptions"].items():
        if m["gap_skill"] not in ids:
            raise ValueError(f"Misconception {code} points to unknown skill")
    _check_acyclic(data["skills"])
    return data


def _check_acyclic(skills: list[dict]) -> None:
    graph = {s["id"]: s["prerequisites"] for s in skills}
    state: dict[str, int] = {}

    def visit(n: str) -> None:
        if state.get(n) == 1:
            raise ValueError(f"Cycle in skill map at {n}")
        if state.get(n) == 2:
            return
        state[n] = 1
        for p in graph[n]:
            visit(p)
        state[n] = 2

    for n in graph:
        visit(n)


def skills_by_id() -> dict[str, dict]:
    return {s["id"]: s for s in skill_map()["skills"]}


def skill_name(skill_id: str) -> str:
    s = skills_by_id().get(skill_id)
    return s["name"] if s else skill_id


def misconceptions() -> dict[str, dict]:
    return skill_map()["misconceptions"]


@lru_cache(maxsize=1)
def questions() -> dict[str, dict]:
    data = _read(DATA_DIR / "questions.json")
    out: dict[str, dict] = {}
    known = set(skills_by_id())
    mis = misconceptions()
    all_qs = list(data["questions"]) + [q for tf in topic_files().values() for q in tf["questions"]]
    for q in all_qs:
        validate_question(q)
        for code in q.get("patterns", {}).values():
            if code not in mis:
                raise ValueError(f"Question {q['id']} uses unknown misconception {code}")
        if q["skill_id"] not in known:
            raise ValueError(f"Question {q['id']} uses unknown skill {q['skill_id']}")
        if q["id"] in out:
            raise ValueError(f"Duplicate question id {q['id']}")
        out[q["id"]] = q
    return out


def questions_in_pool(pool: str) -> list[dict]:
    return [q for q in questions().values() if q["pool"] == pool]


def public_question(q: dict) -> dict:
    """Question as sent to the student: no answer included."""
    return {
        "code": q.get("code"),
        "id": q["id"],
        "skill_id": q["skill_id"],
        "skill_name": skill_name(q["skill_id"]),
        "type": q["type"],
        "prompt": render_prompt(q),
        "input_kind": answer_input_kind(q),
        "choices": choices(q),
    }


@lru_cache(maxsize=1)
def lessons() -> dict[str, dict]:
    data = dict(_read(DATA_DIR / "lessons.json"))
    for tf in topic_files().values():
        data.update(tf["lessons"])
    known = set(skills_by_id())
    for sid, lesson in data.items():
        if sid not in known:
            raise ValueError(f"Lesson for unknown skill {sid}")
        for ex in lesson["worked_examples"]:
            if "type" in ex:  # fraction example: computed exactly by the fractions engine
                validate_question({"id": f"lesson-{sid}", "pool": "lesson", "skill_id": sid, **ex})
            elif not (ex.get("prompt") and ex.get("answer") and ex.get("steps")):
                raise ValueError(f"Lesson {sid}: worked example needs prompt, answer and steps")
    return data


def _check_topics() -> None:
    known = skills_by_id()
    qs = questions()
    for tid, t in topics().items():
        for sk in t["skills"]:
            if sk not in known:
                raise ValueError(f"Topic {tid} lists unknown skill {sk}")
        for label, pool in t["diagnostic_pools"].items():
            if not any(q["pool"] == pool for q in qs.values()):
                raise ValueError(f"Topic {tid}: diagnostic pool {pool} is empty")


def validate_all() -> dict:
    """Load everything once; raises on any content error. Used at startup and in tests."""
    _check_topics()
    return {
        "subjects": len(curriculum()["subjects"]),
        "topics": len(topics()),
        "skills": len(skill_map()["skills"]),
        "misconceptions": len(misconceptions()),
        "questions": len(questions()),
        "lessons": len(lessons()),
    }
